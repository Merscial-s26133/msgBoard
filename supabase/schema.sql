create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(btrim(author)) between 1 and 80),
  text text not null check (char_length(btrim(text)) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;

grant select, insert on public.messages to anon;
grant usage, select on sequence public.messages_id_seq to anon;

drop policy if exists "Public can read messages" on public.messages;
create policy "Public can read messages"
  on public.messages
  for select
  to anon
  using (true);

drop policy if exists "Public can insert messages" on public.messages;
create policy "Public can insert messages"
  on public.messages
  for insert
  to anon
  with check (
    char_length(btrim(author)) between 1 and 80
    and char_length(btrim(text)) between 1 and 2000
  );
